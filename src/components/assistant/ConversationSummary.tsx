import React, { useState } from 'react';
import { TriageResultData, ConversationState } from '../../types/assistant';
import { X, Copy, Check, Printer, AlertTriangle, FileText, CheckCircle2 } from 'lucide-react';

interface ConversationSummaryProps {
  result: TriageResultData;
  state: ConversationState;
  onClose: () => void;
}

export const ConversationSummary: React.FC<ConversationSummaryProps> = ({
  result,
  state,
  onClose,
}) => {
  const [copied, setCopied] = useState(false);

  // Compile formatted summary
  const formattedSummaryText = `=====================================================
PAWCARE VETERINARY TRIAGE & SYMPTOM SUMMARY
=====================================================
Report Generated: ${new Date(result.generatedAt).toLocaleString()}
Animal Species: ${result.animalType.toUpperCase()}
Observed Category: ${result.concernCategory}
Assessed Urgency: ${result.urgencyTitle}

-----------------------------------------------------
1. OBSERVED SYMPTOMS & ANSWERS:
-----------------------------------------------------
${Object.values(state.answers)
  .map(
    (ans, idx) =>
      `Q${idx + 1}: ${ans.questionText}\nAnswer: ${
        ans.selectedChoiceLabels.join(', ') || 'No choice selected'
      }${ans.freeTextAnswer ? ` (Notes: ${ans.freeTextAnswer})` : ''}${
        ans.isUnknown ? ' [MARKED AS UNCERTAIN/NOT SURE]' : ''
      }`
  )
  .join('\n\n')}

-----------------------------------------------------
2. CRITICAL WARNING SIGNS IDENTIFIED:
-----------------------------------------------------
${
  result.emergencyIndicators.length > 0
    ? result.emergencyIndicators
        .map((ind) => `* [${ind.severity.toUpperCase()}] ${ind.title}: ${ind.description}`)
        .join('\n')
    : 'None of the predefined deterministic emergency flags were triggered.'
}

Uncertain/Unknown Responses: ${result.unknownAnswersCount} question(s) marked as Not Sure.

-----------------------------------------------------
3. SAFE IMMEDIATE INTERIM STEPS:
-----------------------------------------------------
${result.safeInterimSteps.map((s, idx) => `${idx + 1}. ${s}`).join('\n')}

-----------------------------------------------------
4. WHAT NOT TO DO (CRITICAL CAUTIONS):
-----------------------------------------------------
${result.whatNotToDo.map((d) => `* ${d}`).join('\n')}

${
  result.reasonForReferral
    ? `-----------------------------------------------------\n5. REASON FOR VETERINARY REFERRAL:\n-----------------------------------------------------\n${result.reasonForReferral}\n`
    : ''
}
-----------------------------------------------------
PRELIMINARY GUIDANCE DISCLAIMER:
This summary was generated by the PawCare animal first-aid triage system.
It is an observational aid to assist clinical examination by a licensed
veterinarian, NOT a confirmed diagnosis.
=====================================================`;

  const handleCopy = () => {
    navigator.clipboard.writeText(formattedSummaryText);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-xs animate-fadeIn">
      <div className="bg-white rounded-2xl max-w-2xl w-full max-h-[90vh] flex flex-col shadow-2xl border border-brand-border overflow-hidden">
        {/* Modal Header */}
        <div className="px-6 py-4 border-b border-brand-border flex items-center justify-between bg-brand-offwhite">
          <div className="flex items-center gap-2.5">
            <FileText className="w-5 h-5 text-brand-forest" />
            <div>
              <h3 className="font-heading font-bold text-base text-brand-charcoal">
                Shareable Veterinarian Summary
              </h3>
              <p className="text-xs text-brand-muted">
                Show this report directly to the attending veterinarian or clinic staff
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-brand-muted hover:text-brand-charcoal hover:bg-brand-sage/40 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Modal Content */}
        <div className="p-6 overflow-y-auto space-y-4 text-xs sm:text-sm font-sans text-brand-charcoal">
          {/* Quick Stats Grid */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-2.5 p-3 rounded-xl bg-brand-beigeLight border border-brand-beige">
            <div>
              <span className="text-[10px] uppercase text-brand-muted font-bold">Animal</span>
              <p className="font-semibold text-brand-charcoal capitalize">{result.animalType}</p>
            </div>
            <div>
              <span className="text-[10px] uppercase text-brand-muted font-bold">Concern</span>
              <p className="font-semibold text-brand-charcoal capitalize">{result.concernCategory}</p>
            </div>
            <div>
              <span className="text-[10px] uppercase text-brand-muted font-bold">Urgency</span>
              <p
                className={`font-semibold capitalize ${
                  result.urgency === 'emergency'
                    ? 'text-red-600'
                    : result.urgency === 'veterinary_assessment'
                    ? 'text-amber-600'
                    : 'text-emerald-700'
                }`}
              >
                {result.urgency.replace('_', ' ')}
              </p>
            </div>
            <div>
              <span className="text-[10px] uppercase text-brand-muted font-bold">Unknowns</span>
              <p className="font-semibold text-brand-charcoal">{result.unknownAnswersCount}</p>
            </div>
          </div>

          {/* Formatted Text Box */}
          <div className="relative">
            <pre className="p-4 bg-brand-offwhite rounded-xl border border-brand-border font-mono text-[11px] leading-relaxed text-brand-charcoal overflow-x-auto whitespace-pre-wrap select-all max-h-80">
              {formattedSummaryText}
            </pre>
          </div>
        </div>

        {/* Modal Footer */}
        <div className="px-6 py-4 border-t border-brand-border bg-brand-offwhite flex flex-wrap items-center justify-between gap-3">
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="px-4 py-2.5 rounded-xl bg-brand-forest hover:bg-brand-forestLight text-white font-semibold text-xs flex items-center gap-1.5 shadow-xs transition-colors"
            >
              {copied ? (
                <>
                  <Check className="w-4 h-4 text-white" />
                  <span>Copied to Clipboard!</span>
                </>
              ) : (
                <>
                  <Copy className="w-4 h-4" />
                  <span>Copy Clean Text</span>
                </>
              )}
            </button>

            <button
              onClick={handlePrint}
              className="px-3.5 py-2.5 rounded-xl bg-white border border-brand-border hover:bg-brand-beigeLight text-brand-charcoal font-medium text-xs flex items-center gap-1.5 transition-colors"
            >
              <Printer className="w-4 h-4 text-brand-muted" />
              <span>Print</span>
            </button>
          </div>

          <button
            onClick={onClose}
            className="px-4 py-2 text-xs font-semibold text-brand-muted hover:text-brand-charcoal"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
